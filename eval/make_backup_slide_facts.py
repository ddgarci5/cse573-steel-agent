def rel(p):
    return str(Path(p).resolve().relative_to(ROOT)).replace("\\", "/")


_cache = {}


def lines_of(path):
    path = Path(path)
    if path not in _cache:
        _cache[path] = path.read_text(encoding="utf-8").splitlines()
    return _cache[path]


def anchor(path, token, nth=1):
    """'file:line' of the nth line containing token. Fails loudly if the token is not in the file."""
    hits = [i + 1 for i, l in enumerate(lines_of(path)) if token in l]
    assert len(hits) >= nth, f"token {token!r} not found in {path}"
    return f"{rel(path)}:{hits[nth - 1]}"


def verbatim(path, token):
    i = int(anchor(path, token).rsplit(":", 1)[1])
    return lines_of(path)[i - 1].strip(), f"{rel(path)}:{i}"


def md_table(header, rows):
    out = ["| " + " | ".join(header) + " |", "|" + "|".join("---" for _ in header) + "|"]
    out += ["| " + " | ".join(str(c) for c in r) + " |" for r in rows]
    return "\n".join(out)


