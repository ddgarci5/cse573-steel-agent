"""Build gold DesignCases for the 13 Dataset C problems, mechanically from datasets/C_benchmark/*.json (no value is changed or re-typed).

Writes datasets/C_benchmark/gold_design_cases.json and results/gold_design_cases_review.md (hand-check table).
Mapping (strength): check -> member_type / task=check_given_section / requested_limit_states (tension only); inputs -> geometry / net_section.
Mapping (selection): task=select_lightest; demands, geometry, constraints copied as they are.
Only what the problem text states is filled; everything else stays null (Cb is stated, and filled, only in the four flexural
strength problems F.1-1B, F.1-2B, F.1-3B and F.3B; it is null in the other nine rows). missing_fields is [] for all 13 (every input the check needs is in the text).

Usage (repo root):  .venv/Scripts/python.exe eval/make_gold_design_cases.py
"""
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))
sys.path.insert(0, str(Path(__file__).resolve().parent))
from agent.design_case import DesignCase  # noqa: E402
import system_c_pilot as S  # noqa: E402  (only build_prompts / HEADER / TAIL_* are used; the file is not modified)

C_DIR = ROOT / "datasets" / "C_benchmark"
LIMIT_STATES = {"tension_yield": ["tension_yield"], "tension_rupture": ["tension_rupture"]}


def problem_texts():
    """problem_id -> the exact problem statement of the System C pilot (its prompt minus the shared header and answer-format tail)."""
    out = {}
    for p in S.build_prompts():
        tail = S.TAIL_NUM if p["kind"] == "strength" else S.TAIL_SEC
        assert p["prompt"].startswith(S.HEADER) and p["prompt"].endswith(tail)
        out[p["id"]] = p["prompt"][len(S.HEADER):-len(tail)]
    return out


def gold_from_strength(c):
    i = c["inputs"]
    d = {"problem_id": c["id"], "member_type": c["member_type"], "task": "check_given_section", "section": c["shape"],
         "requested_limit_states": LIMIT_STATES.get(c["check"], []),
         "geometry": {k: i[k] for k in ("Lcx_ft", "Lcy_ft", "Lb_ft", "Cb") if k in i},
         "net_section": {k: i[k] for k in ("An_in2", "U") if k in i}}
    return d


def gold_from_selection(c):
    return {"problem_id": c["id"], "member_type": c["member_type"], "task": "select_lightest",
            "demands": c["demands"], "geometry": c["geometry"], "constraints": c["constraints"]}


def build():
    texts = problem_texts()
    cases = []
    for fname, conv, key in (("design_examples_strength.json", gold_from_strength, "strength"),
                             ("design_examples_selection.json", gold_from_selection, "selection")):
        for c in json.loads((C_DIR / fname).read_text(encoding="utf-8"))["cases"]:
            dc = DesignCase.model_validate(conv(c))
            assert dc.effective_missing_fields() == [] and dc.flags() == [], (c["id"], dc.flags())
            cases.append({"problem_id": c["id"], "kind": key, "source_file": fname, "problem_text": texts[c["id"]],
                          "design_case": dc.model_dump(mode="json")})
    return cases


def fmt(v):
    return "null" if v is None else (", ".join(v) if isinstance(v, list) and v else ("[]" if v == [] else str(v)))


def review_md(cases):
    L = ["# Gold DesignCases: review sheet", "",
         "**Status: pending Dylan's review.** Nothing below has been hand-checked yet. For each row, read the problem text (the exact statement the models",
         "see, from the System C pilot) and confirm that the gold fields are what a careful engineer would extract: the right member type and task, the",
         "section, the numbers with their units, and null for everything the text does not state. Tick or correct in this file; gold values live in",
         "`datasets/C_benchmark/gold_design_cases.json` and are generated by `eval/make_gold_design_cases.py` from the Dataset C JSON (no value re-typed).", "",
         "Conventions to check: (1) `requested_limit_states` is used only for tension, to say which limit state the question asks for; empty means \"the whole",
         "member\". (2) `Cb` is stated and filled only in the four flexural strength problems (F.1-1B, F.1-2B, F.1-3B, F.3B). It is null in the other nine rows: the",
         "five tension, column and shear strength rows and E.1A (a column, where Lb and Cb do not apply) do not use it, and the three beam selections",
         "(F.1-1A, F.4, F.3A) state no Cb but are continuously braced (Lb = 0), so Cb cannot change the result; it is required only when Lb > 0. (3) `Lb` for F.1-2B is the Dataset C value 35/3 ft = 11.6667 ft; the problem text rounds it to",
         "11.667 ft (0.003 % apart; scoring tolerance is 0.5 %). (4) Material is the A992 default for all 13 (the text states A992 only through the shared",
         "instructions). (5) `missing_fields` is empty for all 13.", ""]
    for c in cases:
        d = c["design_case"]
        rows = [("member_type", d["member_type"]), ("task", d["task"]), ("section", d["section"]),
                ("requested_limit_states", d["requested_limit_states"])]
        for grp in ("demands", "geometry", "net_section", "constraints"):
            rows += [(f"{grp}.{k}", v) for k, v in d[grp].items()]
        rows.append(("missing_fields", d["missing_fields"]))
        L += [f"## {c['problem_id']} ({c['kind']})", "", f"> {c['problem_text']}", "", "| field | gold value |", "|---|---|"]
        L += [f"| `{k}` | {fmt(v)} |" for k, v in rows if v not in (None, []) or k in ("section", "missing_fields", "requested_limit_states")]
        nulls = [k for k, v in rows if v is None and k != "section"]
        L += ["", f"Null (not stated): {', '.join(nulls) if nulls else 'none'}.", "",
              f"Material: {d['material']['grade']} (Fy {d['material']['Fy_ksi']:g}, Fu {d['material']['Fu_ksi']:g}, E {d['material']['E_ksi']:g} ksi); method {d['design_method']}.",
              "", "Reviewer: [ ] correct  [ ] needs change: ________", ""]
    return "\n".join(L)


if __name__ == "__main__":
    cases = build()
    out = {"dataset": "C_benchmark", "set": "gold_design_cases", "purpose": "gold DesignCase per Dataset C problem; extraction ground truth for System D step 1 (evaluation only, never training)",
           "generated_by": "eval/make_gold_design_cases.py", "review_status": "pending Dylan's review", "n_cases": len(cases), "cases": cases}
    (C_DIR / "gold_design_cases.json").write_text(json.dumps(out, indent=2) + "\n", encoding="utf-8")
    (ROOT / "results" / "gold_design_cases_review.md").write_text(review_md(cases) + "\n", encoding="utf-8")
    print(f"wrote {len(cases)} gold cases")
